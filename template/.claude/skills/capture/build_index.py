"""Build the vault's generated index files from the articles. Plain Python, standard library only.

  python build_index.py [vault]           write index.md (the root) and catalog.md
  python build_index.py [vault] --check   write nothing; exit 1 if either file is out of date

Never edit index.md or catalog.md by hand: edit an article, then run this. The frontmatter and link parsing comes from
vault_parse.py, which check.py also uses, so the check and the builder always agree.
"""
import argparse
import re
import sys
from pathlib import Path

sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from vault_parse import links, parse_frontmatter  # noqa: E402,F401  (parse_frontmatter is part of this module's interface)

VAULT = Path(__file__).resolve().parents[3]
SKIP_DIRS = {".git", ".obsidian", ".claude", ".trash", "archive"}
SCHEME = "Vault topics"
REVIEWS = "Reviews"
PREFERENCES = "Preferences"
ROOT_BUDGET = 8000   # characters; the hook adds about 350 and Claude Code inlines up to 10,000
RECENT = 10
SENTENCE_MAX = 160
MARKER = ("<!-- Generated by .claude/skills/capture/build_index.py from the articles. "
          "Do not edit by hand: edit an article, then rebuild. -->")
LEVELS = [("Weekly", re.compile(r"^\d{4}-W\d\d$")), ("Monthly", re.compile(r"^\d{4}-\d\d$")),
          ("Quarterly", re.compile(r"^\d{4}-Q\d$")), ("Yearly", re.compile(r"^\d{4}$"))]
WIKI = re.compile(r"\[\[([^\]|#]+)(?:#[^\]|]*)?(?:\|([^\]]+))?\]\]")
FOOTNOTE = re.compile(r"\[\^[^\]]+\]")
SENTENCE = re.compile(r"^(.+?[.!?])(?=\s|$)")
LOG_LINE = re.compile(r"^(?:- )?(\d{4}-\d\d-\d\d) \| \w+ \| (.*)$")   # capture writes no "- "; older lines have it


def as_list(v):
    return v if isinstance(v, list) else ([v] if v else [])


def summary_sentence(body):
    """The first sentence of the line after the H1, as plain text, cut to 160 characters."""
    lines = body.split("\n")
    line = ""
    for i, l in enumerate(lines):
        if l.startswith("# "):
            line = next((n for n in lines[i + 1:] if n.strip()), "")
            break
    if line.startswith("#"):
        return ""
    text = WIKI.sub(lambda m: m.group(2) or m.group(1), FOOTNOTE.sub("", line)).strip()
    m = SENTENCE.match(text)
    text = m.group(1) if m else text
    if len(text) > SENTENCE_MAX:
        text = text[:SENTENCE_MAX - 3].rsplit(" ", 1)[0] + "..."
    return text


def load(vault=VAULT):
    """{"articles": {title: {...}}, "log": text} for every note one folder deep, outside skipped folders."""
    vault = Path(vault)
    arts = {}
    for p in sorted(vault.glob("*/*.md")):
        folder = p.parent.name
        if folder in SKIP_DIRS or folder.startswith("."):
            continue
        fm, body = parse_frontmatter(p.read_text(encoding="utf-8"))
        kind = fm.get("type") if isinstance(fm.get("type"), str) else ""
        arts[p.stem] = {
            "folder": folder,
            "type": kind,
            "aliases": [a for a in as_list(fm.get("aliases")) if isinstance(a, str)],
            "topics": links(fm.get("topics")),
            "in_scheme": links(fm.get("in_scheme")),
            "review": folder == REVIEWS or kind == "review",
            "sentence": summary_sentence(body),
        }
    log = vault / "log.md"
    return {"articles": arts, "log": log.read_text(encoding="utf-8").replace("\r\n", "\n") if log.exists() else ""}


def hubs(arts):
    return sorted((t for t, a in arts.items() if a["in_scheme"] == [SCHEME] and not a["review"]), key=str.lower)


def members(arts, hub):
    return sorted((t for t, a in arts.items() if hub in a["topics"] and not a["review"]), key=str.lower)


def recent(log, arts, n=RECENT):
    """[(date, title)] for the n newest distinct articles named in log.md, newest first.

    A line names the article whose title or alias it starts with. Failing that, it names every
    title or alias in it as a whole word, matched case-sensitively, longest match first.
    """
    names = {}
    for t, a in arts.items():
        if not a["review"]:
            for name in [t] + a["aliases"]:
                names.setdefault(name, t)
    ordered = sorted(names, key=len, reverse=True)
    pattern = {x: re.compile(r"(?<!\w)" + re.escape(x) + r"(?!\w)") for x in ordered}
    out, seen = [], set()
    for line in reversed(log.split("\n")):
        m = LOG_LINE.match(line)
        if not m:
            continue
        day, text = m.groups()
        lead = next((x for x in ordered if pattern[x].match(text)), None)
        if lead:
            found = [names[lead]]
        else:
            hits = sorted((mm.start(), -len(x), mm.end(), names[x]) for x in ordered for mm in pattern[x].finditer(text))
            found, last_end = [], -1
            for start, _, end, t in hits:
                if start >= last_end:
                    found.append(t)
                    last_end = end
        for t in found:
            if t not in seen:
                seen.add(t)
                out.append((day, t))
                if len(out) == n:
                    return out
    return out


def review_periods(arts):
    """[(level, period, title)] for every review titled 'Vault rollup, <period>'."""
    out = []
    for t, a in arts.items():
        if a["review"] and ", " in t:
            period = t.rsplit(", ", 1)[1]
            level = next((name for name, rx in LEVELS if rx.match(period)), None)
            if level:
                out.append((level, period, t))
    return out


def latest_reviews(arts):
    best = {}
    for level, period, t in review_periods(arts):
        if level not in best or period > best[level][0]:
            best[level] = (period, t)
    return [(name, best[name][1]) for name, _ in LEVELS if name in best]


def render_root(v):
    arts = v["articles"]
    prefs = sorted((t for t, a in arts.items() if a["folder"] == PREFERENCES), key=str.lower)
    L = [MARKER, "# Index", "",
         "The vault's entry point. Topics group every article, and `catalog.md` lists each article under its topic. "
         "Open only what the task needs. Rules are in README.md.",
         "", "## Recently changed", ""]
    L += [f"- {day} [[{t}]]: {arts[t]['sentence']}" for day, t in recent(v["log"], arts)]
    L += ["", "## Topics", ""]
    L += [f"- [[{h}]] ({len(members(arts, h))}): {arts[h]['sentence']}" for h in hubs(arts)]
    L += ["", "## Preferences", "", "Core ones load every session. The rest load on demand by hook (see `.claude/hooks/pref_loader.py`); open one yourself if no hook did and the task fits.", "",
          ", ".join(f"[[{t}]]" for t in prefs)]
    latest = latest_reviews(arts)
    if latest:
        L += ["", "## Latest reviews", ""] + [f"- {level}: [[{t}]]" for level, t in latest]
    L += ["", "Every article by topic: `catalog.md`. Browse by type: the vault's folders.", ""]
    return "\n".join(L)


def render_catalog(v):
    arts = v["articles"]
    L = [MARKER, "# Catalog", "", "Every article, filed under its topics. An article with several topics appears under each one. Only the hubs are links; article titles are plain text, so the graph reaches an article through its hub."]
    for h in hubs(arts):
        L += ["", f"## [[{h}]]", "", arts[h]["sentence"], ""]
        L += [f"- {t} ({(arts[t]['type'] or arts[t]['folder']).capitalize()}): {arts[t]['sentence']}"
              for t in members(arts, h)]
    reviews = review_periods(arts)
    if reviews:
        order = {name: i for i, (name, _) in enumerate(LEVELS)}
        groups = {}
        for level, period, t in reviews:
            groups.setdefault((order[level], level, period[:4]), []).append((period, t))
        L += ["", "## Reviews", ""]
        L += [f"- {level}, {year}: " + ", ".join(t for _, t in sorted(items))
              for (_, level, year), items in sorted(groups.items())]
    L.append("")
    return "\n".join(L)


def build(vault=VAULT, check=False):
    """Write index.md and catalog.md (or, with check, only compare). Returns (stale names, {name: text})."""
    vault = Path(vault)
    v = load(vault)
    outputs = {"index.md": render_root(v), "catalog.md": render_catalog(v)}
    stale = []
    for name, text in outputs.items():
        p = vault / name
        current = p.read_text(encoding="utf-8").replace("\r\n", "\n") if p.exists() else None
        if current != text:
            stale.append(name)
            if not check:
                p.write_bytes(text.encode("utf-8"))
    return stale, outputs


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("vault", nargs="?", default=str(VAULT))
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if a file is out of date")
    args = ap.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    stale, out = build(args.vault, args.check)
    if args.check:
        if stale:
            print("INDEX_STALE " + " ".join(stale) + ": run build_index.py")
            sys.exit(1)
        print("INDEX_CURRENT")
    else:
        print(f"INDEX_BUILT root={len(out['index.md'])} catalog={len(out['catalog.md'])}")


if __name__ == "__main__":
    main()
