"""Copy one canonical instructions file to each agent harness's global instruction file.

  python sync_global_instructions.py CANONICAL [--targets claude codex gemini] [--home DIR] [--dry-run] [--replace]

CANONICAL is the one file you edit, for example a markdown file in a private repo that names your vault and tells every
agent to follow the vault's AGENTS.md. This script writes it, with a "generated" header, to:

  claude  ~/.claude/CLAUDE.md
  codex   ~/.codex/AGENTS.md
  gemini  ~/.gemini/GEMINI.md

By default it writes only to harnesses whose folder already exists in your home folder, so it does not create folders
for tools you do not use. Pass --targets to name harnesses explicitly, which creates their folders.

It never deletes anything. A target that exists and was not generated by this script is skipped and reported, because
it may hold your own hand-written instructions. Pass --replace to overwrite it after saving a copy beside it as
<name>.bak-YYYYMMDD. Run it again whenever the canonical file changes, or schedule it at logon. Standard library only.
"""
import argparse
import sys
from datetime import date
from pathlib import Path

TARGETS = {
    "claude": (".claude", "CLAUDE.md"),
    "codex": (".codex", "AGENTS.md"),
    "gemini": (".gemini", "GEMINI.md"),
}
MARKER = "<!-- Generated by sync_global_instructions.py from"


def header(canonical):
    return f"{MARKER} {canonical}. Edit that file, not this one. -->\n\n"


def sync(canonical, home, names, dry_run=False, replace=False, say=print):
    """Write the canonical file to each named harness. Returns the number of targets skipped."""
    canonical = Path(canonical).resolve()
    body = header(canonical) + canonical.read_text(encoding="utf-8").replace("\r\n", "\n")
    skipped = 0
    for name in names:
        folder, filename = TARGETS[name]
        target = Path(home) / folder / filename
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.exists() else None
        if current == body:
            say(f"same        {target}")
            continue
        if current is not None and not current.startswith(MARKER):
            if not replace:
                say(f"SKIPPED     {target} was not generated by this script; pass --replace to back it up and overwrite")
                skipped += 1
                continue
            backup = target.with_name(f"{target.name}.bak-{date.today():%Y%m%d}")
            if backup.exists():
                say(f"SKIPPED     {target}: {backup.name} already exists; move it aside and run again")
                skipped += 1
                continue
            say(f"{'would back up' if dry_run else 'backed up':<11} {target} -> {backup.name}")
            if not dry_run:
                backup.write_text(current, encoding="utf-8", newline="\n")
        say(f"{'would write' if dry_run else 'wrote':<11} {target}")
        if not dry_run:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(body, encoding="utf-8", newline="\n")
    return skipped


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("canonical", help="the one file you edit")
    ap.add_argument("--targets", nargs="+", choices=sorted(TARGETS), help="harnesses to write; creates their folders")
    ap.add_argument("--home", default=str(Path.home()), help="home folder to write under (default: yours)")
    ap.add_argument("--dry-run", action="store_true", help="show what would be written and change nothing")
    ap.add_argument("--replace", action="store_true", help="overwrite a hand-written target after backing it up")
    args = ap.parse_args(argv)
    if not Path(args.canonical).is_file():
        print(f"error: {args.canonical} is not a file")
        return 2
    names = args.targets or [n for n, (folder, _) in TARGETS.items() if (Path(args.home) / folder).is_dir()]
    if not names:
        print("No harness folders found under the home folder. Pass --targets to choose some.")
        return 1
    return 1 if sync(args.canonical, args.home, names, args.dry_run, args.replace) else 0


if __name__ == "__main__":
    sys.exit(main())
